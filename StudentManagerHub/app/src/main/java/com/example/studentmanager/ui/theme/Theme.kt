@Immutable
data class StatusColors(
    val present: Color,
    val presentContainer: Color,
    val absent: Color,
    val absentContainer: Color,
    val leave: Color,
    val leaveContainer: Color
)

private val LightStatusColors = StatusColors(
    present = LightPresent,
    presentContainer = LightPresentContainer,
    absent = LightAbsent,
    absentContainer = LightAbsentContainer,
    leave = LightLeave,
    leaveContainer = LightLeaveContainer
)

private val DarkStatusColors = StatusColors(
    present = DarkPresent,
    presentContainer = DarkPresentContainer,
    absent = DarkAbsent,
    absentContainer = DarkAbsentContainer,
    leave = DarkLeave,
    leaveContainer = DarkLeaveContainer
)

val LocalStatusColors = staticCompositionLocalOf { LightStatusColors }

/** Entry point for attendance / mark status palettes. */
object AppTheme {
    val statusColors: StatusColors
        @Composable
        @ReadOnlyComposable
        get() = LocalStatusColors.current
}

@Composable
fun StudentManagerHubTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val statusColors = if (darkTheme) DarkStatusColors else LightStatusColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            val controller = WindowCompat.getInsetsController(window, view)
            // Keep system bar icons readable when the in-app theme and the
            // system theme disagree.
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalStatusColors provides statusColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            shapes = AppShapes,
            content = content
        )
    }
}
